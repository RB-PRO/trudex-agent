    final = {}
    src_used = {}
    for line in open("egrul_raw.jsonl", encoding="utf-8"):
        st = json.loads(line)
        rows = (st.get("resp") or {}).get("rows") or []
        if rows:
            final[st["inn"]] = {"inn": st["inn"], "resp": {"rows": rows}}
            src_used[st["inn"]] = "egrul.nalog.ru (эталон)"
